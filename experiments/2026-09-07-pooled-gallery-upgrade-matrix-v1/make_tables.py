def predictions_table(preds: list[dict]) -> tuple[str, int, int]:
    q_label = {
        "Q1_spread": "pooled v0.2 nDCG@5 on ArxivQA $\\le .90$",
        "Q2_cross_vendor_collapse": "cross-vendor stale nDCG@5 $\\le .10$; v0.2 stale within .05",
        "Q3_exact_cut": "exact cut TA@10 = 1.0",
        "Q4_top1_flip": "v0.2 stale top-1 flip $\\ge .10$",
        "Q5_hot_refresh": "matched hot-refresh TA@10 $< .5$; PCA-256 $\\ge .8$",
        "Q6_leverage_budget": "leverage lower at 602k px, in [.60,.85]",
        "Q7_fidelity_at_scale": "PCA-256 nDCG@5 within .01 of target",
        "Q8_composition": "token pooling composes (TA $\\ge .8$, $\\Delta$nDCG $\\le .02$)",
    }
    rows = [(i, d, h) for i, d, h in PRIOR] + [(p["id"].split("_")[0], q_label[p["id"]], p["holds"]) for p in preds]
    n = len(rows); held = sum(1 for r in rows if r[2] is True)
    body = "\n".join(f"    {i} & {d} & {'held' if h is True else ('failed' if h is False else 'n/a')} \\\\" for i, d, h in rows)
    tex = f"""% generated by experiments/2026-09-07-pooled-gallery-upgrade-matrix-v1/make_tables.py
\\begin{{table}}[t]
  \\caption{{Every prediction frozen before GPU output ({held} of {n} held). F: codec
  frontier; I: InfoVQA; B: batch control; C: ColQwen2; P: learned codec and
  cross-vendor transfer; S: sensitivity spectrum; Q: pooled gallery.}}
  \\label{{tab:predictions}}
  \\centering
  \\scriptsize
  \\setlength{{\\tabcolsep}}{{2pt}}
  \\renewcommand{{\\arraystretch}}{{0.92}}
  \\begin{{tabular}}{{@{{}}lp{{0.78\\columnwidth}}l@{{}}}}
    \\toprule
    Id & Prediction & Outcome \\\\
    \\midrule
{body}
    \\bottomrule
  \\end{{tabular}}
\\end{{table}}
"""
    return tex, n, held


def anatomy_rows(res_b: dict) -> str:
    g = res_b["stage_seconds_per_page"]
    t = res_b["tokens_per_page"]["visual"]
    rows = []
    for tname in ("vidore-v0.2",):
        suf = g[f"suffix_target/{tname}"]
        lev = (g["preprocess"] + g["prefix"]) / (g["preprocess"] + g["prefix"] + suf)
        rep = res_b["replay_seconds_per_page"][f"{tname}/pca256_int8"]
        saving = 1 - rep / (g["preprocess"] + g["prefix"] + suf)
        rows.append(f"    pooled, 602k px & {t:.0f} & {g['preprocess']:.3f} & {g['prefix']:.3f} & {suf:.3f} & {lev:.3f} & {rep:.3f} & {100 * saving:.1f}\\% \\\\")
    return "\n".join(rows)


def main() -> None:
    root_a, root_b, paper = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
    res_a = load(root_a); res_b = load(root_b)
    (paper / "tables" / "upgrade_matrix.tex").write_text(upgrade_matrix(res_a))
    preds = predictions(res_a, res_b)
    tex, n, held = predictions_table(preds)
    (paper / "tables" / "predictions.tex").write_text(tex)
    # anatomy: add pooled rows under both budgets (replace any previous generated rows)
    ap = paper / "tables" / "anatomy.tex"; s = ap.read_text()
    s = re.sub(r"\n    pooled, [^\n]*\\\\", "", s)
    ga = res_a["stage_seconds_per_page"]; ta = res_a["tokens_per_page"]["visual"]
    sufa = ga["suffix_target/vidore-v0.2"]; leva = (ga["preprocess"] + ga["prefix"]) / (ga["preprocess"] + ga["prefix"] + sufa)
    repa = res_a["replay_seconds_per_page"]["vidore-v0.2/pca256_int8"]; sava = 1 - repa / (ga["preprocess"] + ga["prefix"] + sufa)
    row_a = f"    pooled, 12.8M px & {ta:.0f} & {ga['preprocess']:.3f} & {ga['prefix']:.3f} & {sufa:.3f} & {leva:.3f} & {repa:.3f} & {100 * sava:.1f}\\% \\\\"
    s = s.replace("    flickr & 226 & 0.010 & 0.054 & 0.056 & 0.535 & 0.055 & 54.4\\% \\\\", "    flickr & 226 & 0.010 & 0.054 & 0.056 & 0.535 & 0.055 & 54.4\\% \\\\\n" + row_a + "\n" + anatomy_rows(res_b))
    ap.write_text(s)

    # placeholders
    T = res_a["targets"]
    def m(t, r, k): return T[t]["metrics"][r][k]
    flips = [m(t, "stale", "top1_flip_rate") for t in T]
    stale_cross = [m(t, "stale", "ndcg_at_5") for t in ("metric-ai-3b", "tsystems-3b")]
    hr_m = [m(t, "hot_refresh@matched", "top10_overlap") for t in T]; hr_h = [m(t, "hot_refresh@0.5", "top10_overlap") for t in T]
    pca_ta = [m(t, "pca256_int8", "top10_overlap") for t in T]
    pca_d = [abs(m(t, "pca256_int8", "ndcg_at_5") - m(t, "target_full", "ndcg_at_5")) for t in T]
    matched = [T[t]["suffix_share_matched_fraction"] for t in T]
    gb = res_b["stage_seconds_per_page"]; ga = res_a["stage_seconds_per_page"]
    full_a = ga["preprocess"] + ga["prefix"] + ga["suffix_target/vidore-v0.2"]; full_b = gb["preprocess"] + gb["prefix"] + gb["suffix_target/vidore-v0.2"]
    lev_b = res_b["cut_leverage"]; lev_a = res_a["cut_leverage"]
    bridge_nd = [m("metric-ai-3b", r, "ndcg_at_5") for r in ("procrustes_bridge", "affine_bridge")]
    bridge_ta = [m("metric-ai-3b", r, "top10_overlap") for r in ("procrustes_bridge", "affine_bridge")]
    pooled = {t: (m(t, "pooled_target_full", "top10_overlap"), m(t, "pooled_target_full", "ndcg_at_5") - m(t, "target_full", "ndcg_at_5"), m(t, "pooled_pca256_int8", "top10_overlap")) for t in T if "pooled_pca256_int8" in T[t]["metrics"]}
    v02 = T["vidore-v0.2"]["metrics"]
    q_fail = [p for p in preds if p["holds"] is False]
    ph = {
        "@@FLIP-V02": pct(v02["stale"]["top1_flip_rate"]),
        "@@TGT-METRIC": f3(m("metric-ai-3b", "target_full", "ndcg_at_5")),
        "@@STALE-METRIC": f3(m("metric-ai-3b", "stale", "ndcg_at_5")),
        "@@STALE-TSYS": f3(m("tsystems-3b", "stale", "ndcg_at_5")),
        "@@STALE-NOMIC": f3(m("colnomic-3b", "stale", "ndcg_at_5")),
        "@@FLIP-NOMIC": pct(m("colnomic-3b", "stale", "top1_flip_rate")),
        "@@FLIP-RANGE": f"{pct(min(flips))}--{pct(max(flips))}",
        "@@STALE-MAX": f3(max(stale_cross)),
        "@@CUT-COST": f"{pct(min(matched))}--{pct(max(matched))}" if abs(max(matched) - min(matched)) > 0.005 else pct(sum(matched) / len(matched)),
        "@@V02-DNDCG": f"{v02['stale']['ndcg_at_5'] - v02['target_full']['ndcg_at_5']:+.3f}",
        "@@TA-STALE-V02": f3(v02["stale"]["top10_overlap"]),
        "@@BRIDGE-METRIC": f"{f3(min(bridge_nd))}--{f3(max(bridge_nd))}",
        "@@BRIDGE-TA-METRIC": f"{f3(min(bridge_ta))}--{f3(max(bridge_ta))}",
        "@@MATCHED-FRAC": f"{pct(min(matched))}--{pct(max(matched))}" if abs(max(matched) - min(matched)) > 0.005 else pct(sum(matched) / len(matched)),
        "@@HR-MATCHED-RANGE": f"{f3(min(hr_m))}--{f3(max(hr_m))}",
        "@@HR-HALF-RANGE": f"{f3(min(hr_h))}--{f3(max(hr_h))}",
        "@@PCA256-TA-RANGE": f"{f3(min(pca_ta))}--{f3(max(pca_ta))}",
        "@@PCA256-DNDCG-MAX": f"{max(pca_d):.3f}".lstrip("0"),
        "@@POOLED-FRONTIER": f"{f3(v02['int8_token']['top10_overlap'])} (INT8), {f3(v02['pca512_int8']['top10_overlap'])} (PCA-512), {f3(v02['pca256_int8']['top10_overlap'])} (PCA-256) and {f3(v02['pca128_int8']['top10_overlap'])} (PCA-128)",
        "@@POOLED-TARGET-TA": "--".join(sorted({f3(v[0]) for v in pooled.values()})),
        "@@POOLED-TARGET-DNDCG": "/".join(f"{v[1]:+.3f}" for v in pooled.values()),
        "@@POOLED-CUT-TA": "--".join(sorted({f3(v[2]) for v in pooled.values()})),
        "@@X-FASTER": f"{full_a / full_b:.1f}$\\times$",
        "@@LEV-602K": f3(lev_b["vidore-v0.2"]),
        "@@N-PRED": str(n), "@@N-HOLD": str(held),
        "@@Q-FAILS": ("On the pooled gallery " + "; ".join(f"{p['id'].split('_')[0]} failed ({p['evidence']})" for p in q_fail) + ".") if q_fail else "All eight pooled-gallery predictions held.",
    }
    (HERE / "analysis-output").mkdir(exist_ok=True)
    (HERE / "analysis-output" / "placeholders.json").write_text(json.dumps(ph, indent=2) + "\n")
    print(json.dumps(ph, indent=2))


if __name__ == "__main__":
    main()
