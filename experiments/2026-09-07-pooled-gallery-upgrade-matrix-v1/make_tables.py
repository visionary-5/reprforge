#!/usr/bin/env python3
"""Generate paper tables and the placeholder map from the pooled-gallery results.

usage: make_tables.py raw-output/output-12845056 raw-output/output-602112 <paper_dir>
Writes <paper_dir>/tables/upgrade_matrix.tex, tables/predictions.tex, appends the
602k rows to tables/anatomy.tex, and writes analysis-output/placeholders.json
(placeholder -> text) consumed by fill_placeholders.py.
"""
from __future__ import annotations

