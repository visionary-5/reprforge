    ("F2", "TA@10 monotone along INT8, INT4, PCA-512/256/128/64", True),
    ("F3", "leverage $\\ge .8$ on documents, lower on Flickr; saving $\\le$ leverage", True),
    ("F4", "in-domain bridges below every codec's TA@10", True),
    ("I1--3", "InfoVQA: exact = 1.0, PCA-256 TA@10 in [.83,.92], leverage $\\ge .85$", True),
    ("B1", "batch-4 control: leverage rises; exact = 1.0", True),
    ("C1", "ColQwen2: exact = 1.0", True),
    ("C2", "ColQwen2 leverage in [.6,.8] (assumed 602k px; run used 12.8M: .87--.90)", False),
