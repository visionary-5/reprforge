from analyze import load, predictions  # noqa: E402

TARGET_LABEL = {"vidore-v0.2": "vidore v0.2", "metric-ai-3b": "Metric-AI", "tsystems-3b": "T-Systems", "colnomic-3b": "ColNomic"}
ROUTES = [
    ("target_full", "full re-encode (reference)"),
    ("stale", "stale index"),
    ("procrustes_bridge", "Procrustes bridge"),
    ("affine_bridge", "affine ridge bridge"),
    ("hot_refresh@matched", "partial re-encode, matched GPU"),
    ("hot_refresh@0.5", "partial re-encode, 50\\% of pages"),
    ("bf16", "exact cut (BF16)"),
    ("int8_token", "cut INT8/token"),
    ("pca512_int8", "cut PCA-512 INT8"),
    ("pca256_int8", "cut PCA-256 INT8"),
    ("pca128_int8", "cut PCA-128 INT8"),
]


def f3(x: float) -> str:
    s = f"{x:.3f}"
    return s[1:] if s.startswith("0") else s


def pct(x: float) -> str:
    return f"{100 * x:.0f}\\%"


def gpu_share(res: dict, tname: str, route: str) -> float | None:
    g = res["stage_seconds_per_page"]
    full = g["preprocess"] + g["prefix"] + g[f"suffix_target/{tname}"]
    if route == "target_full":
        return 1.0
    if route in ("stale", "procrustes_bridge", "affine_bridge"):
        return 0.0
    if route.startswith("hot_refresh"):
        return res["targets"][tname]["hot_refresh_fractions"][route.split("@")[1]]
    key = f"{tname}/{route}"
    if key in res["replay_seconds_per_page"]:
        return res["replay_seconds_per_page"][key] / full
    return None


def upgrade_matrix(res: dict) -> str:
    T = res["targets"]
    names = [n for n in TARGET_LABEL if n in T]
    head = " & ".join(f"\\multicolumn{{3}}{{c}}{{{TARGET_LABEL[n]}}}" for n in names)
    sub = " & ".join("nDCG@5 & flip & TA@10" for _ in names)
    rows = []
    for route, label in ROUTES:
        cells = []
        for n in names:
            m = T[n]["metrics"].get(route)
            if m is None:
                cells.append("-- & -- & --")
            else:
                cells.append(f"{f3(m['ndcg_at_5'])} & {f3(m['top1_flip_rate'])} & {f3(m['top10_overlap'])}")
        shares = [gpu_share(res, n, route) for n in names if gpu_share(res, n, route) is not None]
        gpu = pct(sum(shares) / len(shares)) if shares else "--"
        pb = res["payload_bytes_per_page"].get(route)
        store = f"{pb / res['terminal_bytes_per_page']['float32']:.2f}$\\times$" if pb else "--"
        rows.append(f"    {label} & {' & '.join(cells)} & {gpu} & {store} \\\\")
        if route in ("affine_bridge", "hot_refresh@0.5"):
            rows.append("    \\midrule")
    matched = {n: T[n]["suffix_share_matched_fraction"] for n in names}
    caption = (
        f"Four public upgrades of the deployed ColQwen2.5 v0.1 index on the pooled gallery "
        f"({res['gallery']['pages']:,} pages, {res['gallery']['queries_total']:,} queries, base processor contract, one A100). "
        "nDCG@5 against the single relevant page; top-1 flip rate and TA@10 against the exact target index. "
        "GPU: the route's encode time as a share of a full re-encode (matched hot-refresh re-encodes "
        + "--".join(f"{v:.0f}\\%" for v in sorted({round(100 * v) for v in matched.values()}))
        + " of pages; partial re-encode is hot-refresh without compatible training); storage: retained bytes over the float32 terminal tensor. Extra codecs were run for the first two upgrades."
    )
    body = "\n".join(rows)
    return f"""% generated by experiments/2026-09-07-pooled-gallery-upgrade-matrix-v1/make_tables.py
\\begin{{table*}}[t]
  \\caption{{{caption}}}
  \\label{{tab:upgrades}}
  \\centering
  \\footnotesize
  \\setlength{{\\tabcolsep}}{{3.2pt}}
  \\begin{{tabular}}{{l{'rrr' * len(names)}rr}}
    \\toprule
    & {head} & & \\\\
    Route & {sub} & GPU & Storage \\\\
    \\midrule
{body}
    \\bottomrule
  \\end{{tabular}}
\\end{{table*}}
"""


